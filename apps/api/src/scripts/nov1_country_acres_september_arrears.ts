/**
 * 11/1 — SEPTEMBER AT COUNTRY ACRES, FOR THE PEOPLE WHO DID NOT PAY.
 *
 * Blue's handwritten sheet carries two columns, September and October. GAM's
 * first billing at Country Acres was OCTOBER, so September exists nowhere on
 * the platform. The eight lots that paid September are money already collected
 * and go in as income (country-acres-september-collected.csv). This script is
 * the other three: the ones who did not pay.
 *
 * Nic, 11/1:
 *   "The people that haven't paid, it doesn't need to go on the profit and
 *    loss statement as a loss. It needs to go on their outstanding moved out
 *    still owed list."
 *   "Money always rides the most outstanding balance first."
 *
 * WHY A CARRIED BALANCE AND NOT A NEW INVOICE. GAM already has the shape for
 * this and has since S605: `invoices.is_opening_balance` — "a balance carried
 * in from the landlord's prior system, not generated by the billing engine" —
 * with its own `carried_balance` charge type and ONE per lease
 * (ux_invoices_one_opening_balance_per_lease). Inventing a second mechanism
 * would have put the same debt in two shapes. The P&L counts only money that
 * actually settled, so an unpaid carried balance shows as owed and never as
 * income or as a loss, which is exactly what Nic asked for.
 *
 * THE LATE FEE IS AN EXPLICIT LINE, NOT AN ACCRUAL. Each of these owes a $50
 * late fee for September, the same $50 the engine already charged them for
 * October (five late fees dated 10/06 are already on the books). It is written
 * here as its own late_fee row, mirroring October exactly, rather than left to
 * the accrual engine — the debt is historic and finished, so a fee that keeps
 * growing from a month that already closed would be wrong. The invoice is
 * therefore late_fee_exempt.
 *
 * NATHAN'S $500 MOVES. He paid $100 on 9/3 and $400 since, $500 in all, and
 * GAM applied the $400 to OCTOBER because September did not exist yet. Under
 * Nic's oldest-first rule it belongs to September. That $400 is a rent row
 * marked settled by hand (manual_method 'bank_deposit') — no card, no ACH, no
 * Stripe intent — so re-pointing it is bookkeeping and touches no money rail.
 * October goes back to fully owed; September shows $500 received against it.
 *
 * KYRA IS GONE. Her lease is still active and her space is in eviction mode.
 * She owes September and October and nothing after, so the lease ends 10/31
 * and the space comes out of eviction mode. Ending it runs the pull-back that
 * went live today, which voids her November charges by itself — that is the
 * whole point of the end date, so it is stated and not guessed.
 *
 * SUSIE IS ALREADY OUT. Her lease expired 10/31 and Heather's replacement
 * started 11/1; November on that lot is entirely Heather's. She needs her
 * September balance and nothing else.
 *
 * Run with DRY=1 to print what it would do and change nothing.
 */
import { getClient } from '../db'
import { allocateInvoiceNumber } from '../services/invoiceNumbers'

const DRY = process.env.DRY === '1'
const PARK = 'Country Acres - Mattoon'
const SEPT_DUE = '2026-09-01'

/** What Blue's sheet says each of these was billed for September. */
const ARREARS = [
  { lot: 'MH 18', who: 'Kyra Smith',      septBill: 566.50,          lateFee: 50, paid: 0 },
  { lot: 'MH 28', who: 'Susie McCoy',     septBill: 692.90,          lateFee: 50, paid: 0 },
  { lot: 'MH 29', who: 'Nathan Mitchell', septBill: 669.80,          lateFee: 50, paid: 500 },
] as const

async function main() {
  const c = await getClient()
  const say = (s: string) => console.log(s)
  try {
    await c.query('BEGIN')

    for (const a of ARREARS) {
      // The lease each of them held IN SEPTEMBER — for Susie that is the
      // expired one, not Heather's replacement. Newest start that began on or
      // before September, so a later lease on the same lot cannot win it.
      const lease = (await c.query<{
        lease_id: string; tenant_id: string; landlord_id: string; unit_id: string; status: string
      }>(`
        SELECT l.id AS lease_id, lt.tenant_id, l.landlord_id, l.unit_id, l.status
          FROM leases l
          JOIN units u ON u.id = l.unit_id
          JOIN properties p ON p.id = u.property_id
          LEFT JOIN LATERAL (
            SELECT tenant_id FROM lease_tenants
             WHERE lease_id = l.id AND role = 'primary' ORDER BY created_at LIMIT 1
          ) lt ON TRUE
         WHERE p.name = $1 AND u.unit_number = $2 AND l.start_date <= $3::date
         ORDER BY l.start_date DESC LIMIT 1`, [PARK, a.lot, SEPT_DUE])).rows[0]

      if (!lease) { say(`${a.lot}: NO LEASE covering September — skipped`); continue }
      if (!lease.tenant_id) { say(`${a.lot}: lease has no primary tenant — skipped`); continue }

      const already = (await c.query(
        `SELECT id FROM invoices WHERE lease_id = $1 AND is_opening_balance = TRUE`,
        [lease.lease_id])).rows[0]
      if (already) { say(`${a.lot}: already has a carried balance — skipped (nothing double-entered)`); continue }

      const owed = a.septBill + a.lateFee - a.paid
      say(`${a.lot}  ${a.who}  (${lease.status} lease)`)
      say(`    September billed ${a.septBill.toFixed(2)} + late fee ${a.lateFee.toFixed(2)}`
        + (a.paid ? ` − paid ${a.paid.toFixed(2)}` : '') + `  →  owes ${owed.toFixed(2)}`)
      if (DRY) continue

      const invoiceNumber = await allocateInvoiceNumber(c, lease.landlord_id, 2026)
      const inv = (await c.query<{ id: string }>(`
        INSERT INTO invoices (
          landlord_id, tenant_id, lease_id, unit_id, invoice_number, due_date,
          subtotal_rent, subtotal_fees, subtotal_utilities, subtotal_late_fees,
          total_amount, status, is_opening_balance, late_fee_exempt
        ) VALUES ($1,$2,$3,$4,$5,$6::date, 0,0,0,$7, $8, 'pending', TRUE, TRUE)
        RETURNING id`,
        [lease.landlord_id, lease.tenant_id, lease.lease_id, lease.unit_id,
         invoiceNumber, SEPT_DUE, a.lateFee.toFixed(2), a.septBill.toFixed(2)])).rows[0]

      const note = `September 2026 at ${PARK} — billed before this park was on GAM, never paid.`

      // The September bill itself. Where money was received against it, the
      // paid part is its own settled row and the rest stays owed — the same
      // split GAM already uses on Nathan's October (400 settled + 50 open).
      if (a.paid > 0) {
        await c.query(
          `INSERT INTO payments (invoice_id, unit_id, lease_id, tenant_id, landlord_id,
             type, amount, status, due_date, settled_at, processed_at,
             entry_description, notes, manual_method, import_source, imported_at)
           VALUES ($1,$2,$3,$4,$5,'carried_balance',$6,'settled',$7::date,$7::date,$7::date,
                   'BALANCE',$8,'bank_deposit','manual',NOW())`,
          [inv.id, lease.unit_id, lease.lease_id, lease.tenant_id, lease.landlord_id,
           a.paid.toFixed(2), SEPT_DUE,
           `${note} Paid toward it: $${a.paid.toFixed(2)}, oldest balance first.`])
      }
      const stillOwed = a.septBill - a.paid
      if (stillOwed > 0) {
        await c.query(
          `INSERT INTO payments (invoice_id, unit_id, lease_id, tenant_id, landlord_id,
             type, amount, status, due_date, entry_description, notes, import_source, imported_at)
           VALUES ($1,$2,$3,$4,$5,'carried_balance',$6,'pending',$7::date,'BALANCE',$8,'manual',NOW())`,
          [inv.id, lease.unit_id, lease.lease_id, lease.tenant_id, lease.landlord_id,
           stillOwed.toFixed(2), SEPT_DUE, note])
      }
      // September's late fee, as its own line, exactly like October's.
      await c.query(
        `INSERT INTO payments (invoice_id, unit_id, lease_id, tenant_id, landlord_id,
           type, amount, status, due_date, entry_description, notes, import_source, imported_at)
         VALUES ($1,$2,$3,$4,$5,'late_fee',$6,'pending',$7::date,'LATEFEE',$8,'manual',NOW())`,
        [inv.id, lease.unit_id, lease.lease_id, lease.tenant_id, lease.landlord_id,
         a.lateFee.toFixed(2), SEPT_DUE,
         'Late fee for September 2026 — the same $50 charged for October.'])
      say(`    → carried balance ${invoiceNumber} written`)
    }

    // ── NATHAN'S $400 MOVES OFF OCTOBER ──────────────────────────────────
    // It was applied to October only because September did not exist. Oldest
    // first means it is September's. The row is a hand-recorded bank deposit,
    // so this re-opens a charge and moves nothing through any payment rail.
    const oct400 = (await c.query<{ id: string }>(`
      SELECT p.id FROM payments p
      JOIN units u ON u.id = p.unit_id JOIN properties pr ON pr.id = u.property_id
      WHERE pr.name = $1 AND u.unit_number = 'MH 29'
        AND p.type = 'rent' AND p.status = 'settled' AND p.amount = 400
        AND p.due_date = '2026-10-01'::date AND p.stripe_payment_intent_id IS NULL`,
      [PARK])).rows[0]
    if (!oct400) {
      say(`MH 29: the $400 on October is not where it was — left alone, check by hand`)
    } else {
      say(`MH 29: moving the $400 off October (it is September's under oldest-first)`)
      if (!DRY) {
        await c.query(
          `UPDATE payments
              SET status = 'pending', settled_at = NULL, processed_at = NULL,
                  manual_method = NULL,
                  notes = LEFT(CONCAT_WS(' — ', NULLIF(notes,''),
                    'Re-applied to September 2026, which was older and unpaid; money rides the oldest balance first.'), 2000)
            WHERE id = $1`, [oct400.id])
      }
    }

    // ── KYRA IS GONE ─────────────────────────────────────────────────────
    const kyra = (await c.query<{ lease_id: string; unit_id: string }>(`
      SELECT l.id AS lease_id, u.id AS unit_id
        FROM leases l JOIN units u ON u.id = l.unit_id JOIN properties p ON p.id = u.property_id
       WHERE p.name = $1 AND u.unit_number = 'MH 18' AND l.status = 'active'`, [PARK])).rows[0]
    if (kyra) {
      say(`MH 18: ending Kyra's lease on 2026-10-31 and clearing eviction mode`)
      if (!DRY) {
        await c.query(
          `UPDATE leases SET end_date = '2026-10-31'::date, updated_at = NOW() WHERE id = $1`,
          [kyra.lease_id])
        await c.query(
          `UPDATE units
              SET payment_block = FALSE, payment_block_set_at = NULL, payment_block_set_by = NULL,
                  status = COALESCE(status_before_block, status), status_before_block = NULL,
                  updated_at = NOW()
            WHERE id = $1`, [kyra.unit_id])
      }
      say(`    (the nightly lease-end sweep pulls her November charges back by itself)`)
    } else {
      say(`MH 18: no active lease to end — already done`)
    }

    if (DRY) { await c.query('ROLLBACK'); say('\nDRY RUN — nothing written.') }
    else { await c.query('COMMIT'); say('\nApplied.') }
  } catch (e) {
    await c.query('ROLLBACK').catch(() => {})
    throw e
  } finally { c.release() }
}

main().then(() => process.exit(0)).catch(e => { console.error(e); process.exit(1) })
