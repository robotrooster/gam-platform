-- WHERE a contractor can buy the top spot, and what it costs there.
--
-- 10/31 (Nic): "Paid spot per trade per area code should be based on cost of
-- living in the area. LA/NY prices don't touch Wyoming or Oklahoma. Let's
-- figure a base formula and a monthly rate schedule."
--
-- THE AREA IS A METRO, OR THE REST OF A STATE, AND NOT A TELEPHONE AREA CODE —
-- for one reason, which is that every price has to trace to a published number.
-- Cost of living is published per metro area and per state by the Bureau of
-- Economic Analysis (Regional Price Parities). It is not published per area
-- code, and mapping 335 area codes onto metros would mean inventing the figure
-- that sets the price. So the territory is BEA's own geography: 388 metro areas
-- plus "the rest of <state>" for everywhere outside one, which covers the
-- country with no gaps and no invented numbers. A contractor who thinks in area
-- codes can still be shown their area by typing one — that is a lookup, not the
-- pricing key, and the area_kind column leaves room for 'area_code' rows if Nic
-- wants the territory itself redrawn.
--
-- THE INDEX is BEA Regional Price Parity, all items, 2024 (the latest published
-- year), US = 100. Every row below is the published figure to three decimals,
-- straight from SARPP (states) and MARPP (metros) at apps.bea.gov/regional —
-- nothing is interpolated, smoothed or estimated. The real spread is Monroe, LA
-- at 83.6 to San Francisco at 115.6.
--
-- "The rest of <state>" carries the STATE's figure, which includes that state's
-- metros and is therefore a little high for genuinely rural ground. Said out
-- loud rather than quietly fudged: it is the only published number that covers
-- those places, and BEA does not publish a nonmetropolitan-portion RPP.
--
-- ANNUAL REFRESH. BEA publishes the new year each December. A new year is NEW
-- ROWS with a later index_year, never an UPDATE, so a spot sold at last year's
-- index can still be explained. Goes on the November list beside the deposit-
-- interest and state-tax-form refresh.
--
-- No backfill: new table, nothing read it before.

CREATE TABLE IF NOT EXISTS marketplace_areas (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- 'metro'       — a BEA metropolitan statistical area; area_key is its CBSA code
  -- 'state_rural' — everywhere in that state outside a metro; area_key is the
  --                 two-letter state
  area_kind text NOT NULL,
  area_key text NOT NULL,
  name text NOT NULL,
  -- Every state the area touches. A metro can cross state lines (New
  -- York-Newark-Jersey City is NY-NJ), so this is a list and not a column.
  states text[] NOT NULL DEFAULT ARRAY[]::text[],
  cost_index numeric(6,3) NOT NULL,
  index_source text NOT NULL,
  index_year integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT NOW(),
  updated_at timestamptz NOT NULL DEFAULT NOW()
);

ALTER TABLE marketplace_areas DROP CONSTRAINT IF EXISTS marketplace_areas_kind;
ALTER TABLE marketplace_areas ADD CONSTRAINT marketplace_areas_kind
  CHECK (area_kind IN ('metro', 'state_rural', 'area_code'));

-- A cost of living of zero would price a spot at whatever the bottom band says
-- instead of refusing, so the index has to be a real figure.
ALTER TABLE marketplace_areas DROP CONSTRAINT IF EXISTS marketplace_areas_index_real;
ALTER TABLE marketplace_areas ADD CONSTRAINT marketplace_areas_index_real
  CHECK (cost_index > 0);

DROP INDEX IF EXISTS ux_marketplace_areas_key;
CREATE UNIQUE INDEX ux_marketplace_areas_key
  ON marketplace_areas(area_kind, area_key, index_year);

CREATE INDEX IF NOT EXISTS ix_marketplace_areas_states ON marketplace_areas USING GIN (states);

